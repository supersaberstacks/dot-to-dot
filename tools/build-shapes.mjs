// Build step. Drives trace.html in a headless browser and writes ../shapes.js.
//
//   node tools/build-shapes.mjs
//
// Run this only when the subject list changes. The generated shapes.js is
// committed, so end users never trace anything and every device draws the
// identical puzzle for a given seed.

import { execFileSync } from "node:child_process";
import { writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));

const CANDIDATES = [
  process.env.CHROME_PATH,
  "C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe",
  "C:/Program Files/Microsoft/Edge/Application/msedge.exe",
  "C:/Program Files/Google/Chrome/Application/chrome.exe",
  "C:/Program Files (x86)/Google/Chrome/Application/chrome.exe",
  "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
  "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
  "/usr/bin/google-chrome",
  "/usr/bin/chromium",
  "/usr/bin/chromium-browser"
].filter(Boolean);

const browser = CANDIDATES.find(p => existsSync(p));
if (!browser) {
  console.error("No Chrome/Edge found. Set CHROME_PATH to a Chromium binary.");
  process.exit(1);
}

const page = "file:///" + join(here, "trace.html").replace(/\\/g, "/");
console.log("tracing with " + browser);

const dom = execFileSync(
  browser,
  ["--headless", "--disable-gpu", "--virtual-time-budget=20000", "--dump-dom", page],
  { encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }
);

const m = dom.match(/<pre id="out">([\s\S]*?)<\/pre>/);
if (!m || !m[1].trim()) {
  console.error("Tracer produced no output - open tools/trace.html in a browser to debug.");
  process.exit(1);
}

// The tracer emits only JSON-safe ASCII, but &<> would still be escaped in DOM text.
const json = m[1].replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">");
const { shapes, rejected } = JSON.parse(json);

if (!shapes.length) {
  console.error("Every subject was rejected - is an emoji font installed?");
  process.exit(1);
}

shapes.sort((a, b) => a.name.localeCompare(b.name));

// `node tools/build-shapes.mjs --diag robot` explains what happened to every
// candidate part for a subject, which beats guessing why one looks wrong.
const want = process.argv.indexOf("--diag");
if (want !== -1) {
  const target = (process.argv[want + 1] || "").toLowerCase();
  for (const s of shapes) {
    if (target && s.name.toLowerCase() !== target) continue;
    console.log(`\n${s.name} - ${s.parts.length} parts, ${s.corners} corners`);
    console.log("  kind    area%   circ   taut    hug   outcome");
    for (const d of s.diag)
      console.log(`  ${d.kind.padEnd(7)} ${(d.share * 100).toFixed(1).padStart(5)}  ` +
                  `${d.circ.toFixed(2).padStart(5)}  ${d.taut.toFixed(2).padStart(5)}  ` +
                  `${d.hug.toFixed(2).padStart(5)}   ${d.why}`);
  }
}

for (const s of shapes) delete s.diag;   // diagnostics never ship

const body = shapes.map(s => {
  const parts = s.parts
    .map(p => `      { perim: ${p.perim}, p: [${p.p.join(",")}] }`)
    .join(",\n");
  return `  {\n    name: ${JSON.stringify(s.name)}, corners: ${s.corners},\n` +
         `    parts: [\n${parts}\n    ]\n  }`;
}).join(",\n");

const out = `// GENERATED by tools/build-shapes.mjs - do not edit by hand.
// ${shapes.length} subjects, normalised into a 0..1000 box.
// parts[0] is the silhouette; any further parts are interior detail, in the
// same coordinate frame. "corners" measures how much structure the outline has.
window.DOT_SHAPES = [
${body}
];
`;

writeFileSync(join(here, "..", "shapes.js"), out, "utf8");

const pts = shapes.reduce((s, x) => s + x.parts.reduce((t, p) => t + p.p.length / 2, 0), 0);
const withDetail = shapes.filter(s => s.parts.length > 1).length;
console.log(`wrote shapes.js - ${shapes.length} subjects, ${pts} points, ${(out.length / 1024).toFixed(0)} KB`);
console.log(`  ${withDetail} have interior detail, ${shapes.length - withDetail} silhouette-only`);
for (const [name, why] of rejected) console.log(`  rejected ${name}: ${why}`);
